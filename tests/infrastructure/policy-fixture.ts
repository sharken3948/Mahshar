/** Synthetic test policy only; none of these ceilings are Production defaults. */
export function enableTestBudgets() {
  Object.assign(process.env, {
    MAHSHAR_GROQ_BUDGET_ENABLED: 'true',
    MAHSHAR_GROQ_REQUESTS_MINUTE: '30', MAHSHAR_GROQ_REQUESTS_DAY: '2000', MAHSHAR_GROQ_UNITS_DAY: '8000000',
    MAHSHAR_GROQ_CONCURRENCY: '8', MAHSHAR_GROQ_MAX_OUTPUT_TOKENS: '8192', MAHSHAR_GROQ_MAX_PROMPT_BYTES: '131072',
    MAHSHAR_GROQ_MATCH_REQUESTS_DAY: '1000', MAHSHAR_GROQ_MATCH_UNITS_DAY: '4000000',
    MAHSHAR_GROQ_SCORE_REQUESTS_DAY: '500', MAHSHAR_GROQ_SCORE_UNITS_DAY: '2000000',
    MAHSHAR_GROQ_BACKGROUND_REQUESTS_DAY: '1000', MAHSHAR_GROQ_BACKGROUND_UNITS_DAY: '2000000',
    MAHSHAR_LISTING_CREATE_BUDGET_ENABLED: 'true', MAHSHAR_LISTING_CREATE_GLOBAL_DAY: '200', MAHSHAR_LISTING_CREATE_WALLET_DAY: '20',
    MAHSHAR_VERIFICATION_BUDGET_ENABLED: 'true', MAHSHAR_VERIFICATION_GLOBAL_DAY: '1000', MAHSHAR_VERIFICATION_WALLET_DAY: '100', MAHSHAR_VERIFICATION_CONCURRENCY: '8',
    MAHSHAR_ONRAMP_BUDGET_ENABLED: 'true', MAHSHAR_ONRAMP_GLOBAL_DAY: '1000', MAHSHAR_ONRAMP_WALLET_DAY: '20', MAHSHAR_ONRAMP_CONCURRENCY: '8',
  })
}

export function disableTestBudgets() {
  for (const key of Object.keys(process.env)) {
    if (/^MAHSHAR_(GROQ_|LISTING_CREATE_|VERIFICATION_|ONRAMP_)/.test(key)) delete process.env[key]
  }
}
